#!/usr/bin/env python3
"""Estimate contamination-free OBS baseline prognosis with an RSF.

The development train and validation cohorts are pooled.  Only patients who
actually received observation (OBS) are used to tune or fit a prognostic
model.  In the default ``nested`` mode, every OBS prediction is generated by
an outer-fold model whose Optuna search and model fit both excluded that
patient.  A separate Optuna study on all OBS patients selects the parameters
for a final full-OBS model, which is used only to predict the ACT patients.

The output table compares predicted 60-month OBS RMST between patients whose
observed treatment was aligned versus discordant with a treatment-policy
recommendation.  With no arguments, those groups are generated using honest
development predictions from a newly tuned and fitted RSF T-learner. Prior
T-learner performance is used only to choose plausible Optuna search bounds;
no fitted model, selected parameters, or frozen recommendation is reused. An
optional patient-level CSV containing either ``recommendation`` or
``alignment`` can override the default by setting ``ALIGNMENT_FILE`` below.

Example
-------
    /Users/owensun/miniconda3/bin/python \
      test_for_hte/obs_rsf_baseline_prognosis.py

If configured, the alignment CSV must contain the patient identifier
(``patient_id`` by default) plus one of:

* ``recommendation``: OBS/ACT or 0/1; alignment is calculated against actual
  treatment.
* ``alignment``: aligned/discordant or a boolean/0/1 value.

The 18 clinical features are prespecified. If ``GENE_LIST`` is set, that list
must also be prespecified or selected without using the assessed patients'
outcomes; this script intentionally does not pretend that an externally
outcome-selected gene list is made honest by downstream folds.

Set ``SELECTION_MODE = "global"`` for the conventional, faster workflow in
which one all-OBS Optuna study supplies the parameters for the outer-fold
models. Its model fits still exclude each held-out patient, but the patient's
outcome participates in global hyperparameter selection; the default
``"nested"`` mode avoids that subtler source of contamination.
"""

